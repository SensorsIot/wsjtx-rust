"""The role guard and the candidate bench: the tester may start, stop and query the bench of its own
issue with exactly `-Start|-Stop|-Status -Issue <its issue>`, and run a page script of its own run
folder with node; another issue, other arguments, a script elsewhere and every other role are refused.

It judges commands with the installed role files (.claude/agents/<role>.md, regenerated by
install_skills.py from harness/project/docs/Agent-Working-Rules.md) through install_skills.guard,
the function the PreToolUse hook calls. Nothing is run.
"""
import glob
import os
import sys
import unittest
from unittest import mock

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "harness", "general", "core", "tools"))
import install_skills  # noqa: E402

BENCH = "powershell -NoProfile -ExecutionPolicy Bypass -File tools/test/powershell/candidate-bench.ps1"
ALLOWED = (BENCH + " -Start -Issue 1", BENCH + " -Stop -Issue 1", BENCH + " -Status -Issue 1",
           "node D:/wstx-tmp/live/1/case-2.cjs", "node D:/wstx-tmp/live/1/page_read.cjs")
REFUSED = (
    BENCH + " -Start -Issue 2",
    BENCH + " -Start",
    BENCH + " -Start -Issue 1 -Repo D:/wstx-tmp/live/1",
    BENCH + " -Start -Issue 1 -Station D:/wstx-tmp/live/1/station",
    BENCH + " -Start -Issue 1 -BuildRoot D:/x",
    BENCH + " -Start -Issue 1; " + BENCH + " -Stop -Issue 1",
    BENCH + " -Restart -Issue 1",
    BENCH + " -Start -Issue 12",
    "powershell -NoProfile -ExecutionPolicy Bypass -File D:/wstx-tmp/live/1/../../../Github/wsjtx-rust/tools/test/powershell/candidate-bench.ps1 -Start -Issue 1",
    "node D:/wstx-tmp/live/2/case.cjs",
    "node D:/wstx-tmp/live/1/../2/case.cjs",
    "node D:/wstx-tmp/live/1/case.js",
    "node tools/test/node/bench-page.cjs",
    "node -e \"require('child_process')\"",
    "node D:/wstx-tmp/live/1/case.cjs && git push",
)


def roles():
    return sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(ROOT, ".claude", "agents", "*.md")))


class GuardTests(unittest.TestCase):
    def judge(self, role, command, tool="Bash", scoped=True):
        env = {k: v for k, v in os.environ.items() if not k.startswith("HARNESS_ROLE_")}
        env.update(CLAUDE_PROJECT_DIR=ROOT, **({"HARNESS_ROLE_ISSUE": "1"} if scoped else {}))
        with mock.patch.dict(os.environ, env, clear=True):
            return install_skills.guard(role, {"tool_name": tool, "tool_input": {"command": command}, "cwd": ROOT})

    def test_the_tester_may_run_the_bench_of_its_issue_and_a_page_script_of_its_run_folder(self):
        for tool in ("Bash", "PowerShell"):
            for command in ALLOWED:
                self.assertIsNone(self.judge("tester", command, tool), f"{tool}: {command}")

    def test_another_issue_other_arguments_and_scripts_elsewhere_are_refused(self):
        for command in REFUSED:
            self.assertIsNotNone(self.judge("tester", command), command)

    def test_every_other_role_is_refused(self):
        others = [r for r in roles() if r != "tester"]
        self.assertIn("coder", others)
        for role in others:
            for command in ALLOWED:
                self.assertIsNotNone(self.judge(role, command), f"{role}: {command}")

    def test_the_bench_needs_the_runs_scope(self):
        for command in ALLOWED:
            self.assertIsNotNone(self.judge("tester", command, scoped=False), command)


if __name__ == "__main__":
    unittest.main()
