"""The role guard, station-switch.ps1 and emulator.ps1: the tester may switch the station with
exactly `-To simulator` or `-To back` and run the emulator script with exactly `-Start`, `-Stop`
or `-Status`; other arguments and every other role are refused.

It judges commands with the installed role files (.claude/agents/<role>.md, regenerated by
install_skills.py from harness/project/docs/Agent-Working-Rules.md) through install_skills.guard,
the function the PreToolUse hook calls. Nothing is run.
"""
import glob
import os
import sys
import unittest
from unittest import mock

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "harness", "general", "core", "tools"))
import install_skills  # noqa: E402

RUN = "powershell -NoProfile -ExecutionPolicy Bypass -File harness/project/deploy/station-switch.ps1"
EMU = "powershell -NoProfile -ExecutionPolicy Bypass -File harness/project/deploy/emulator.ps1"
UP = "powershell -NoProfile -ExecutionPolicy Bypass -File D:/wstx-tmp/live/1/../../../Github/wsjtx-rust/harness/project/deploy/"
ALLOWED = (RUN + " -To simulator", RUN + " -To back", EMU + " -Start", EMU + " -Stop", EMU + " -Status")
REFUSED = (
    RUN,
    RUN + " -To simulator -DryRun",
    RUN + " -To back -DryRun",
    RUN + " -To simulator -Station D:/wstx-tmp/live/1/station",
    RUN + " -To back -Pin x.ps1",
    RUN + " -To simulator; " + RUN + " -To back",
    RUN + " -To Simulator2",
    RUN + " -To backup",
    UP + "station-switch.ps1 -To back",
    UP + "station-switch.ps1 -To simulator",
    EMU,
    EMU + " -Start -DryRun",
    EMU + " -Stop -DryRun",
    EMU + " -Start -Emulator D:/wstx-tmp/live/1/fake",
    EMU + " -Start -StateDir D:/wstx-tmp/live/1",
    EMU + " -Start -ReadySeconds 1",
    EMU + " -Start -Stop",
    EMU + " -Starts",
    EMU + " -Restart",
    EMU + " -Stop; " + RUN + " -To back",
    EMU + " -Stop && " + RUN + " -To back",
    UP + "emulator.ps1 -Start",
)


def roles():
    return sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(ROOT, ".claude", "agents", "*.md")))


class GuardTests(unittest.TestCase):
    def judge(self, role, command, tool="Bash"):
        with mock.patch.dict(os.environ, {"CLAUDE_PROJECT_DIR": ROOT}):
            return install_skills.guard(role, {"tool_name": tool, "tool_input": {"command": command}, "cwd": ROOT})

    def test_the_tester_may_switch_and_run_the_emulator(self):
        for tool in ("Bash", "PowerShell"):
            for allowed in ALLOWED:
                for command in (allowed, allowed.replace("powershell ", "pwsh.exe ")):
                    self.assertIsNone(self.judge("tester", command, tool), f"{tool}: {command}")

    def test_the_tester_may_not_add_or_change_arguments(self):
        for command in REFUSED:
            self.assertIsNotNone(self.judge("tester", command), command)

    def test_every_other_role_is_refused(self):
        others = [r for r in roles() if r != "tester"]
        self.assertIn("coder", others)
        for role in others:
            for command in (*ALLOWED, *REFUSED):
                self.assertIsNotNone(self.judge(role, command), f"{role}: {command}")

    def test_the_tester_binding_names_the_scripts(self):
        with open(os.path.join(ROOT, ".claude", "agents", "tester.md"), encoding="utf-8") as f:
            text = f.read()
        self.assertIn("station-switch\\\\.ps1 -To (simulator|back)", text, "the installed policy carries the pattern")
        self.assertIn("emulator\\\\.ps1 -(Start|Stop|Status)", text, "the installed policy carries the pattern")


if __name__ == "__main__":
    unittest.main()
