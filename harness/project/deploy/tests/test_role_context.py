"""The project's role additions follow the context map and the run's scope: the tester's live
folder and the prober's experiment folder are its issue's, the prober reads the recordings, the
coder and the reviewer run Node tests and sysml.py only in their own worktree, and the definer
writes nothing.

It judges tool calls with the installed role files (.claude/agents/<role>.md, regenerated by
install_skills.py from harness/project/docs/Agent-Working-Rules.md) through install_skills.guard,
the function the PreToolUse hook calls. Nothing is run.
"""
import os
import sys
import unittest
from unittest import mock

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "harness", "general", "core", "tools"))
import install_skills  # noqa: E402

PS = "powershell -NoProfile -ExecutionPolicy Bypass -File "
WT = ".git/harness-parallel/worktrees/issue-7"
OTHER = ".git/harness-parallel/worktrees/issue-8"
SCOPE = {"HARNESS_ROLE_ISSUE": "7", "HARNESS_ROLE_WORKTREE": os.path.join(ROOT, WT)}


class Context(unittest.TestCase):
    def judge(self, role, tool, given, scoped=True):
        env = {k: v for k, v in os.environ.items() if not k.startswith("HARNESS_ROLE_")}
        env.update(CLAUDE_PROJECT_DIR=ROOT, **(SCOPE if scoped else {}))
        with mock.patch.dict(os.environ, env, clear=True):
            return install_skills.guard(role, {"tool_name": tool, "tool_input": given, "cwd": ROOT})

    def test_the_tester_and_the_prober_work_in_their_issues_folders(self):
        for role, command, path in (
                ("tester", PS + "D:/wstx-tmp/live/7/run.ps1", "D:/wstx-tmp/live/7/log.txt"),
                ("prober", "python D:/wstx-tmp/experiments/7/probe.py", "D:/wstx-tmp/experiments/7/a.py")):
            self.assertIsNone(self.judge(role, "Bash", {"command": command}), command)
            self.assertIsNone(self.judge(role, "Write", {"file_path": path, "content": "x"}), path)
            self.assertIsNone(self.judge(role, "Read", {"file_path": path}), path)
            other = command.replace("/7/", "/8/"), path.replace("/7/", "/8/")
            self.assertIsNotNone(self.judge(role, "Bash", {"command": other[0]}), other[0])
            self.assertIsNotNone(self.judge(role, "Write", {"file_path": other[1], "content": "x"}), other[1])
            self.assertIsNotNone(self.judge(role, "Read", {"file_path": other[1]}), other[1])
            self.assertIsNotNone(self.judge(role, "Bash", {"command": command}, scoped=False), command)

    def test_the_prober_reads_the_recordings_and_no_other_role_does(self):
        recording = os.path.join(ROOT, ".git/migration-data/recordings/a.wav")
        self.assertIsNone(self.judge("prober", "Read", {"file_path": recording}))
        for role in ("tester", "coder", "reviewer", "checker", "definer", "explainer"):
            self.assertIsNotNone(self.judge(role, "Read", {"file_path": recording}), role)

    def test_station_data_is_no_roles_context(self):
        station = os.path.join(os.environ.get("LOCALAPPDATA") or os.path.expanduser("~"), "WstxRust/station/a.json")
        for role in ("tester", "prober", "coder", "reviewer", "checker", "definer", "explainer", "issue-coordinator",
                     "harness-improver"):
            self.assertIsNotNone(self.judge(role, "Read", {"file_path": station}), role)

    def test_node_tests_and_sysml_run_only_in_the_runs_worktree(self):
        for role in ("coder", "reviewer"):
            node = f"node --test {WT}/tests/a.test.cjs"
            self.assertIsNone(self.judge(role, "Bash", {"command": node}), role)
            self.assertIsNotNone(self.judge(role, "Bash", {"command": node.replace(WT, OTHER)}), role)
            self.assertIsNotNone(self.judge(role, "Bash", {"command": node}, scoped=False), role)
        for command in (f"python {WT}/tools/sysml.py oracle", f"python {WT}/tools/sysml.py check"):
            self.assertIsNone(self.judge("coder", "Bash", {"command": command}), command)
            self.assertIsNotNone(self.judge("coder", "Bash", {"command": command.replace(WT, OTHER)}), command)
        self.assertIsNone(self.judge("checker", "Bash", {"command": "python tools/sysml.py check"}, scoped=False))
        self.assertIsNotNone(self.judge("checker", "Bash", {"command": f"python {OTHER}/tools/sysml.py check"}))

    def test_the_definer_writes_nothing(self):
        for path in (os.path.join(ROOT, WT, "docs/sysml/a.sysml"), os.path.join(ROOT, "docs/x.md")):
            self.assertIsNotNone(self.judge("definer", "Write", {"file_path": path, "content": "x"}), path)

    def test_the_checker_posts_its_verdict_on_its_issue_only(self):
        verdict = "gh issue comment {} --body 'Ready: PASS — 0123abc'"
        self.assertIsNone(self.judge("checker", "Bash", {"command": verdict.format(7)}))
        self.assertIsNotNone(self.judge("checker", "Bash", {"command": verdict.format(8)}))
        self.assertIsNotNone(self.judge("checker", "Bash", {"command": verdict.format(7)}, scoped=False))


if __name__ == "__main__":
    unittest.main()
