"""The role guard and station-switch.ps1 (harness#114): the tester may switch the station to the
simulator with exactly `-To simulator`; `-To back` (no agent switches the station to ic7300),
other arguments and every other role are refused.

It judges commands with the installed role files (.claude/agents/<role>.md, regenerated by
install_skills.py from docs/harness/Agent-Working-Rules.md) through install_skills.guard, the
function the PreToolUse hook calls. Nothing is run.
"""
import glob
import os
import sys
import unittest
from unittest import mock

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "harness", "core", "tools"))
import install_skills  # noqa: E402

RUN = "powershell -NoProfile -ExecutionPolicy Bypass -File .harness/deploy/station-switch.ps1"
ALLOWED = RUN + " -To simulator"
REFUSED = (
    RUN + " -To back",
    RUN,
    RUN + " -To simulator -DryRun",
    RUN + " -To simulator -Station D:/wstx-tmp/live/1/station",
    RUN + " -To simulator -Pin x.ps1",
    RUN + " -To simulator; " + RUN + " -To back",
    RUN + " -To Simulator2",
    "powershell -NoProfile -ExecutionPolicy Bypass -File D:/wstx-tmp/live/1/../../../Github/wsjtx-rust/.harness/deploy/station-switch.ps1 -To back",
)


def roles():
    return sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(ROOT, ".claude", "agents", "*.md")))


class GuardTests(unittest.TestCase):
    def judge(self, role, command, tool="Bash"):
        with mock.patch.dict(os.environ, {"CLAUDE_PROJECT_DIR": ROOT}):
            return install_skills.guard(role, {"tool_name": tool, "tool_input": {"command": command}, "cwd": ROOT})

    def test_the_tester_may_switch_to_the_simulator(self):
        for tool in ("Bash", "PowerShell"):
            for command in (ALLOWED, ALLOWED.replace("powershell ", "pwsh.exe ")):
                self.assertIsNone(self.judge("tester", command, tool), f"{tool}: {command}")

    def test_the_tester_may_not_switch_back_or_add_arguments(self):
        for command in REFUSED:
            self.assertIsNotNone(self.judge("tester", command), command)

    def test_every_other_role_is_refused(self):
        others = [r for r in roles() if r != "tester"]
        self.assertIn("coder", others)
        for role in others:
            for command in (ALLOWED, *REFUSED):
                self.assertIsNotNone(self.judge(role, command), f"{role}: {command}")

    def test_the_tester_binding_names_the_script(self):
        with open(os.path.join(ROOT, ".claude", "agents", "tester.md"), encoding="utf-8") as f:
            text = f.read()
        self.assertIn("station-switch\\\\.ps1 -To simulator", text, "the installed policy carries the pattern")


if __name__ == "__main__":
    unittest.main()
